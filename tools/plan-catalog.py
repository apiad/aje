#!/usr/bin/env python3
"""Build the plan catalog from a *133 capture (docs/ussd/133.json, see docs/ussd/README.md).

Every screen that asks to confirm a purchase is a plan: its group is the root option it sits under,
its name the option that led to it, its price the figure after "x" in the confirm text. The catalog
goes to two places: web/core/plancatalog.js, bundled in the app, and site/plans.json, which
aje.apiad.net serves so a price change reaches phones without a release.

    python3 tools/plan-catalog.py
    python3 tools/plan-catalog.py --check   # fails when either output is out of date
"""

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CAPTURE = ROOT / "docs/ussd/133.json"
BUNDLED = ROOT / "web/core/plancatalog.js"
HOSTED = ROOT / "site/plans.json"
PRICE = re.compile(r"\bx\s*(\d+(?:\.\d+)?)")


def build(capture):
    screens = {tuple(s["path"]): s for s in capture["screens"]}
    root = screens[()]
    groups = []
    for option in root["options"]:
        plans = []
        for path, screen in sorted(screens.items(), key=lambda kv: [int(k) for k in kv[0]]):
            if screen["kind"] != "confirm" or path[0] != option["key"]:
                continue
            parent = screens[path[:-1]]
            label = next(o["label"] for o in parent["options"] if o["key"] == path[-1])
            price = PRICE.search(screen["text"])
            if not price:
                sys.exit(f"no price in {screen['code']}: {screen['text']!r}")
            plans.append({
                "path": "*".join(path),
                "name": re.sub(r"\s*x\s*\d+(?:\.\d+)?\s*$", "", label).strip(),
                "price": float(price.group(1)),
                "ask": screen["text"].strip(),
            })
        if plans:
            groups.append({"label": option["label"], "plans": plans})
    return {"v": 1, "captured": capture["captured"], "groups": groups}


def render(catalog):
    hosted = json.dumps(catalog, ensure_ascii=False, indent=2) + "\n"
    bundled = (
        "// Generated by tools/plan-catalog.py from docs/ussd/133.json. Do not edit.\n"
        f"export const BUNDLED = {hosted.rstrip()};\n"
    )
    return {HOSTED: hosted, BUNDLED: bundled}


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail when an output differs from the capture")
    args = parser.parse_args()
    outputs = render(build(json.loads(CAPTURE.read_text())))
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if args.check:
        if stale:
            sys.exit("out of date: " + ", ".join(str(p.relative_to(ROOT)) for p in stale) + "; run tools/plan-catalog.py")
        return
    for path, text in outputs.items():
        path.write_text(text)
    n = sum(len(g["plans"]) for g in json.loads(outputs[HOSTED])["groups"])
    print(f"{n} plans written to {len(outputs)} files")


if __name__ == "__main__":
    main()
